def make_graph_config(GraphBuildConfig):
    """Create the same r=6, n=32 graph config despite minor API-name changes."""
    signature = inspect.signature(GraphBuildConfig)
    kwargs = {}

    for name in signature.parameters:
        if name == "radius":
            kwargs[name] = 6.0
        elif name == "max_neighbors":
            kwargs[name] = 32
        elif name in {"schema_version", "cache_schema_version"}:
            kwargs[name] = 1

    return GraphBuildConfig(**kwargs)


def as_numpy(value):
    if isinstance(value, torch.Tensor):
        return value.detach().cpu().numpy()

    return np.asarray(value)


def sample_get(sample, key, default=None):
    if isinstance(sample, dict):
        return sample.get(key, default)

    try:
        return sample[key]
    except Exception:
        pass

    try:
        return getattr(sample, key)
    except Exception:
        return default


def scalar_value(value, default=None):
    if value is None:
        return default

    if isinstance(value, torch.Tensor):
        if value.numel() == 1:
            return value.item()
        return value.detach().cpu().tolist()

    if isinstance(value, np.ndarray):
        if value.size == 1:
            return value.reshape(-1)[0].item()
        return value.tolist()

    return value


def normalise_id(value):
    return str(scalar_value(value, "")).strip()


def kabsch_transform(mobile, target):
    """Return R,t such that mobile @ R + t best matches target."""
    mobile = np.asarray(mobile, dtype=np.float64)
    target = np.asarray(target, dtype=np.float64)

    if mobile.shape != target.shape:
        raise ValueError(
            f"Kabsch shape mismatch: {mobile.shape} vs {target.shape}"
        )

    if len(mobile) < 3:
        raise ValueError(
            f"Need at least 3 points for rigid alignment; got {len(mobile)}"
        )

    cm = mobile.mean(axis=0)
    ct = target.mean(axis=0)

    x = mobile - cm
    y = target - ct

    covariance = x.T @ y

    u, _, vt = np.linalg.svd(covariance)

    rotation = u @ vt

    if np.linalg.det(rotation) < 0:
        u[:, -1] *= -1.0
        rotation = u @ vt

    translation = ct - cm @ rotation

    return rotation, translation


def apply_transform(coords, rotation, translation):
    return (
        np.asarray(coords, dtype=np.float64) @ rotation
        + translation
    )


def rmsd(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)

    if len(a) == 0:
        return np.nan

    return float(
        np.sqrt(
            np.mean(
                np.sum(
                    (a - b) ** 2,
                    axis=-1,
                )
            )
        )
    )


def residue_node_mapping(sample, n_nodes):
    node_residue = as_numpy(
        sample_get(sample, "node_residue")
    ).astype(np.int64)

    residue_seq_id = as_numpy(
        sample_get(sample, "residue_seq_id")
    ).astype(np.int64)

    if residue_seq_id.ndim != 1:
        residue_seq_id = residue_seq_id.reshape(-1)

    if len(residue_seq_id) == n_nodes:
        return residue_seq_id

    if (
        len(node_residue) == n_nodes
        and len(node_residue)
        and node_residue.max() < len(residue_seq_id)
    ):
        return residue_seq_id[node_residue]

    raise ValueError(
        "Could not map graph nodes to polymer sequence positions: "
        f"n_nodes={n_nodes}, "
        f"len(node_residue)={len(node_residue)}, "
        f"len(residue_seq_id)={len(residue_seq_id)}"
    )


def parse_af3_modelcif(path, prediction_id):
    """Return exact-sequence-position -> atom coordinates for AF3 ModelCIF.

    AF3 predicts a complete monomer chain. We select the chain whose residue
    sequence SHA256 prefix matches the prediction ID. Sequence positions are
    assigned by residue order (1..L), matching the exact sequence used to
    generate the AF3 JSON.
    """
    structure = gemmi.read_structure(str(path))

    if len(structure) == 0:
        raise ValueError(f"No models found in {path}")

    model = structure[0]

    expected_prefix = prediction_id.removeprefix("af3_").lower()

    candidates = []

    for chain in model:
        residues = []

        for residue in chain:
            resname = residue.name.strip().upper()

            aa = AA3_TO_1.get(resname)

            if aa is None:
                continue

            residues.append(
                (residue, aa)
            )

        if not residues:
            continue

        sequence = "".join(
            aa
            for _, aa in residues
        )

        seq_hash = hashlib.sha256(
            sequence.encode("utf-8")
        ).hexdigest()

        candidates.append(
            (
                chain,
                residues,
                sequence,
                seq_hash,
            )
        )

    if not candidates:
        raise ValueError(
            f"No standard-amino-acid chain found in {path}"
        )

    matching = [
        candidate
        for candidate in candidates
        if candidate[3].startswith(expected_prefix)
    ]

    if len(matching) != 1:
        descriptions = [
            {
                "chain": c[0].name,
                "length": len(c[2]),
                "sha16": c[3][:16],
            }
            for c in candidates
        ]

        raise ValueError(
            f"Expected one AF3 chain matching {prediction_id}, "
            f"found {len(matching)}. Candidates: {descriptions}"
        )

    chain, residues, sequence, seq_hash = matching[0]

    atom_coords = {}
    residue_aa = {}

    for seq_pos, (residue, aa) in enumerate(
        residues,
        start=1,
    ):
        residue_aa[seq_pos] = aa

        # Keep the best occupancy when an atom name appears more than once.
        best = {}

        for atom in residue:
            atom_name = atom.name.strip().upper()

            if not atom_name:
                continue

            # We score graph heavy atoms only.
            if atom.element.name.upper() == "H":
                continue

            occupancy = float(atom.occ)

            old = best.get(atom_name)

            if old is None or occupancy > old[0]:
                best[atom_name] = (
                    occupancy,
                    np.array(
                        [
                            atom.pos.x,
                            atom.pos.y,
                            atom.pos.z,
                        ],
                        dtype=np.float64,
                    ),
                )

        for atom_name, (_, coord) in best.items():
            atom_coords[
                (seq_pos, atom_name)
            ] = coord

    return {
        "chain": chain.name,
        "sequence": sequence,
        "sequence_sha256": seq_hash,
        "atom_coords": atom_coords,
        "residue_aa": residue_aa,
    }


def build_prediction_on_graph(
    parsed,
    node_seq_id,
    atom_names,
):
    n_nodes = len(node_seq_id)

    coords = np.full(
        (n_nodes, 3),
        np.nan,
        dtype=np.float64,
    )

    mask = np.zeros(
        n_nodes,
        dtype=bool,
    )

    atom_coords = parsed[
        "atom_coords"
    ]

    for i in range(n_nodes):
        key = (
            int(node_seq_id[i]),
            str(atom_names[i]),
        )

        coord = atom_coords.get(key)

        if coord is not None:
            coords[i] = coord
            mask[i] = True

    return coords, mask


def symmetry_correct(
    pred_aligned,
    target,
    pred_mask,
    target_mask,
    node_seq_id,
    atom_names,
    residue_aa,
):
    """Choose chemically equivalent atom-name permutations by target SSE."""
    corrected = pred_aligned.copy()

    by_residue = defaultdict(dict)

    for i, (seq_id, atom_name) in enumerate(
        zip(node_seq_id, atom_names)
    ):
        by_residue[
            int(seq_id)
        ][str(atom_name)] = i

    def swap_if_better(seq_id, pairs):
        atom_index = by_residue.get(
            int(seq_id),
            {},
        )

        # Require both labels from every pair to exist in both prediction/target.
        pair_indices = []

        for a_name, b_name in pairs:
            ia = atom_index.get(a_name)
            ib = atom_index.get(b_name)

            if ia is None or ib is None:
                return

            if not (
                pred_mask[ia]
                and pred_mask[ib]
                and target_mask[ia]
                and target_mask[ib]
            ):
                return

            pair_indices.append(
                (ia, ib)
            )

        no_swap_sse = 0.0
        swap_sse = 0.0

        for ia, ib in pair_indices:
            no_swap_sse += float(
                np.sum(
                    (
                        corrected[ia]
                        - target[ia]
                    )
                    ** 2
                )
            )
            no_swap_sse += float(
                np.sum(
                    (
                        corrected[ib]
                        - target[ib]
                    )
                    ** 2
                )
            )

            swap_sse += float(
                np.sum(
                    (
                        corrected[ib]
                        - target[ia]
                    )
                    ** 2
                )
            )
            swap_sse += float(
                np.sum(
                    (
                        corrected[ia]
                        - target[ib]
                    )
                    ** 2
                )
            )

        if swap_sse < no_swap_sse:
            old_values = {
                i: corrected[i].copy()
                for pair in pair_indices
                for i in pair
            }

            for ia, ib in pair_indices:
                corrected[ia] = old_values[ib]
                corrected[ib] = old_values[ia]

    for seq_id, aa in residue_aa.items():

        for pair in SIMPLE_SYMMETRY.get(
            aa,
            [],
        ):
            swap_if_better(
                seq_id,
                [pair],
            )

        for coupled in COUPLED_SYMMETRY.get(
            aa,
            [],
        ):
            swap_if_better(
                seq_id,
                list(coupled),
            )

    return corrected


def compute_lddt(
    pred,
    target,
    common_mask,
    node_seq_id,
    radius,
):
    indices = np.where(
        common_mask
    )[0]

    if len(indices) < 2:
        return np.nan, 0

    target_common = target[
        indices
    ]

    tree = cKDTree(
        target_common
    )

    pairs = tree.query_pairs(
        r=float(radius),
        output_type="ndarray",
    )

    if pairs.size == 0:
        return np.nan, 0

    i_global = indices[
        pairs[:, 0]
    ]
    j_global = indices[
        pairs[:, 1]
    ]

    # Standard lDDT-style exclusion of within-residue atom pairs.
    keep = (
        node_seq_id[i_global]
        != node_seq_id[j_global]
    )

    i_global = i_global[keep]
    j_global = j_global[keep]

    if len(i_global) == 0:
        return np.nan, 0

    target_dist = np.linalg.norm(
        target[i_global]
        - target[j_global],
        axis=1,
    )

    pred_dist = np.linalg.norm(
        pred[i_global]
        - pred[j_global],
        axis=1,
    )

    delta = np.abs(
        pred_dist
        - target_dist
    )

    score = float(
        np.mean(
            [
                np.mean(
                    delta < threshold
                )
                for threshold in (
                    0.5,
                    1.0,
                    2.0,
                    4.0,
                )
            ]
        )
    )

    return score, int(
        len(delta)
    )


def evaluate_pair(
    sample,
    parsed_prediction,
    ATOM_NAMES,
    local_radius,
    lddt_radius,
):
    pos_target = as_numpy(
        sample_get(
            sample,
            "pos_target",
        )
    ).astype(
        np.float64
    )

    pos_wt = as_numpy(
        sample_get(
            sample,
            "pos_init",
        )
    ).astype(
        np.float64
    )

    n_nodes = len(
        pos_target
    )

    target_mask = as_numpy(
        sample_get(
            sample,
            "target_mask",
        )
    ).astype(
        bool
    )

    atom_type = as_numpy(
        sample_get(
            sample,
            "atom_type",
        )
    ).astype(
        np.int64
    )

    # Graph construction reserves atom_type == len(ATOM_NAMES) as an
    # unknown/rare atom bucket.  Match the benchmark evaluator: never index
    # ATOM_NAMES blindly, and represent out-of-range IDs as "UNK".
    atom_names = np.asarray(
        [
            (
                ATOM_NAMES[int(i)]
                if 0 <= int(i) < len(ATOM_NAMES)
                else "UNK"
            )
            for i in atom_type
        ],
        dtype=object,
    )

    node_seq_id = residue_node_mapping(
        sample,
        n_nodes,
    )

    pred_raw, pred_mask = build_prediction_on_graph(
        parsed_prediction,
        node_seq_id,
        atom_names,
    )

    is_ca = sample_get(
        sample,
        "is_ca",
    )

    if is_ca is None:
        is_ca = (
            atom_names == "CA"
        )
    else:
        is_ca = as_numpy(
            is_ca
        ).astype(
            bool
        )

    distance_to_mutation = as_numpy(
        sample_get(
            sample,
            "distance_to_mutation",
        )
    ).astype(
        np.float64
    )

    common_ca = (
        is_ca
        & target_mask
        & pred_mask
    )

    ca_indices = np.where(
        common_ca
    )[0]

    if len(ca_indices) < 3:
        raise ValueError(
            f"Only {len(ca_indices)} common C-alpha atoms"
        )

    # ---------------------------------------------------------
    # Global prediction -> experimental target alignment.
    # ---------------------------------------------------------
    global_R, global_t = kabsch_transform(
        pred_raw[ca_indices],
        pos_target[ca_indices],
    )

    pred_target_frame = apply_transform(
        pred_raw,
        global_R,
        global_t,
    )

    ca_rmsd = rmsd(
        pred_target_frame[
            ca_indices
        ],
        pos_target[
            ca_indices
        ],
    )

    # ---------------------------------------------------------
    # Mutation-local CA RMSD in a fixed WT-defined 8 A region.
    # ---------------------------------------------------------
    local_ca_mask = (
        common_ca
        & (
            distance_to_mutation
            <= float(local_radius)
        )
    )

    local_indices = np.where(
        local_ca_mask
    )[0]

    local_ca_rmsd = rmsd(
        pred_target_frame[
            local_indices
        ],
        pos_target[
            local_indices
        ],
    )

    # ---------------------------------------------------------
    # Symmetry-correct prediction for all-atom metrics.
    # ---------------------------------------------------------
    corrected_pred = symmetry_correct(
        pred_target_frame,
        pos_target,
        pred_mask,
        target_mask,
        node_seq_id,
        atom_names,
        parsed_prediction[
            "residue_aa"
        ],
    )

    # ---------------------------------------------------------
    # All-atom lDDT.
    # ---------------------------------------------------------
    common_heavy = (
        target_mask
        & pred_mask
    )

    lddt, lddt_pair_count = compute_lddt(
        corrected_pred,
        pos_target,
        common_heavy,
        node_seq_id,
        lddt_radius,
    )

    # ---------------------------------------------------------
    # Mutation-site side-chain RMSD.
    # ---------------------------------------------------------
    mutation_index_0 = int(
        scalar_value(
            sample_get(
                sample,
                "mutation_index_0",
            )
        )
    )

    mutation_seq_id = (
        mutation_index_0
        + 1
    )

    sidechain_mask = (
        common_heavy
        & (
            node_seq_id
            == mutation_seq_id
        )
        & ~np.isin(
            atom_names,
            list(
                BACKBONE_NAMES
            ),
        )
    )

    sidechain_indices = np.where(
        sidechain_mask
    )[0]

    mutation_sidechain_rmsd = rmsd(
        corrected_pred[
            sidechain_indices
        ],
        pos_target[
            sidechain_indices
        ],
    )

    # ---------------------------------------------------------
    # MR-RMSD8:
    # Compare predicted and native WT->variant CA displacement fields
    # after independently removing global rigid-body motion relative to WT.
    #
    # Use exactly the same common CA set for both alignments.
    # ---------------------------------------------------------
    pred_wt_R, pred_wt_t = kabsch_transform(
        pred_raw[
            ca_indices
        ],
        pos_wt[
            ca_indices
        ],
    )

    target_wt_R, target_wt_t = kabsch_transform(
        pos_target[
            ca_indices
        ],
        pos_wt[
            ca_indices
        ],
    )

    pred_wt_frame = apply_transform(
        pred_raw,
        pred_wt_R,
        pred_wt_t,
    )

    target_wt_frame = apply_transform(
        pos_target,
        target_wt_R,
        target_wt_t,
    )

    delta_pred = (
        pred_wt_frame[
            local_indices
        ]
        - pos_wt[
            local_indices
        ]
    )

    delta_native = (
        target_wt_frame[
            local_indices
        ]
        - pos_wt[
            local_indices
        ]
    )

    mutation_response_rmsd = rmsd(
        delta_pred,
        delta_native,
    )

    return {
        "ca_rmsd": ca_rmsd,
        "lddt": lddt,
        "local_ca_rmsd_8a": local_ca_rmsd,
        "mutation_sidechain_rmsd": mutation_sidechain_rmsd,
        "mutation_response_rmsd_8a": mutation_response_rmsd,
        "common_ca_count": int(
            len(ca_indices)
        ),
        "local_ca_count_8a": int(
            len(local_indices)
        ),
        "common_heavy_atom_count": int(
            common_heavy.sum()
        ),
        "mutation_sidechain_atom_count": int(
            len(sidechain_indices)
        ),
        "lddt_distance_pair_count": int(
            lddt_pair_count
        ),
        "predicted_graph_atom_fraction": float(
            pred_mask.mean()
        ),
        "target_observed_atom_fraction_mapped": float(
            (
                pred_mask
                & target_mask
            ).sum()
            / max(
                int(
                    target_mask.sum()
                ),
                1,
            )
        ),
    }


