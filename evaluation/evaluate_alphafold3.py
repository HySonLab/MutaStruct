#!/usr/bin/env python3
"""Evaluate AlphaFold3 on the locked MutaStruct Tier-A test set.

Expected AF3 structures
-----------------------
Flat directory such as:

  predictions/Alphafold3/af3_tier_a_target_structures/
      af3_<sequence_sha256_prefix>_model.cif
      af3_...._model.cif

Authoritative mapping
---------------------
This script DOES NOT infer the AF3 target from target_sequence.

It uses the locked target mapping generated by af3_inputs_tier_a_targets.py:

  manifests_tier_a_targets/test_pairs_af3_targets.csv

which contains:

  pair_id -> target_prediction_id

This is necessary because AF3 was run on the exact canonical polymer sequence
from the experimental mmCIF entity.

Metrics
-------
The same five primary metrics used for the other MutaStruct models:

1. Global C-alpha RMSD (lower is better)
2. all-atom lDDT (higher is better)
3. Local C-alpha RMSD within the WT-defined 8 A mutation neighborhood
4. Mutation-site side-chain RMSD
5. Mutation-response RMSD within 8 A (MR-RMSD8)

Primary manuscript aggregation is event-macro:
coordinate-pair observations are first averaged within event_id and then
mutation events receive equal weight.

Run
---
conda activate MutaStruct-GT

python evaluate_alphafold3_main5.py

Smoke test:
python evaluate_alphafold3_main5.py --max-cases 32
"""

